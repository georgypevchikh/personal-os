"""Block graph: validate the registry, derive the global state snapshot, stamp freshness.

Two-layer model:
* Structural sync is deterministic and lives here (registry -> generated snapshot).
* Semantic propagation (does this milestone change a public claim?) cannot be
  inferred from frontmatter; the agent follows the event matrix in block-sync.md.
  This module only reports *which* dependent blocks need that review.
"""

from __future__ import annotations

import re
import subprocess
from dataclasses import dataclass

from .vault import Vault, frontmatter


@dataclass
class BlockRow:
    id: str
    kind: str
    title: str
    status: str
    updated: str
    owner: str
    depends_on: list[str]


class GraphError(ValueError):
    def __init__(self, errors: list[str]):
        self.errors = errors
        super().__init__("\n".join(f"- {e}" for e in errors))


def validate(vault: Vault) -> list[BlockRow]:
    errors: list[str] = []
    rows: list[BlockRow] = []
    blocks = vault.registry.get("blocks", [])
    ids = [b.get("id") for b in blocks]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        errors.append(f"duplicate block id(s): {', '.join(map(str, duplicates))}")
    known = set(ids)
    registry_rel = "00-meta/block-registry.json"

    for block in blocks:
        block_id = block.get("id", "<missing>")
        owner_rel = block.get("owner", "")
        owner = vault.path(owner_rel)
        if not owner.is_file():
            errors.append(f"{block_id}: owner does not exist: {owner_rel}")
            continue
        try:
            fm = frontmatter(owner)
        except ValueError as exc:
            errors.append(f"{block_id}: {exc}")
            continue
        for key in ("title", "status", "updated"):
            if not fm.get(key):
                errors.append(f"{block_id}: owner missing `{key}`: {owner_rel}")
        if fm.get("sync_registry") != registry_rel:
            errors.append(f"{block_id}: owner missing canonical `sync_registry: {registry_rel}`: {owner_rel}")
        deps = block.get("depends_on", [])
        unknown = sorted(set(deps) - known)
        if unknown:
            errors.append(f"{block_id}: unknown dependencies: {', '.join(unknown)}")
        if block_id in deps:
            errors.append(f"{block_id}: depends on itself")
        rows.append(
            BlockRow(
                id=block_id,
                kind=block.get("kind", "unknown"),
                title=fm.get("title", block_id),
                status=fm.get("status", "missing"),
                updated=fm.get("updated", "missing"),
                owner=owner_rel,
                depends_on=list(deps),
            )
        )

    dashboard = vault.path(vault.cfg("root_dashboard"))
    if dashboard.is_file():
        text = dashboard.read_text(encoding="utf-8")
        for row in rows:
            if row.kind == "domain" and row.owner.removesuffix(".md") not in text:
                errors.append(f"{row.id}: domain owner is not linked from {vault.cfg('root_dashboard')}")

    context = vault.path(vault.cfg("current_context"))
    if context.is_file():
        current = context.read_text(encoding="utf-8").lower()
        for row in rows:
            if row.kind == "project" and row.status in {"active", "live", "blocked"}:
                if row.id.lower() not in current and row.title.lower() not in current:
                    errors.append(f"{row.id}: live project is absent from {vault.cfg('current_context')}")

    if errors:
        raise GraphError(errors)
    return rows


def render(vault: Vault, rows: list[BlockRow]) -> str:
    lines = [
        "---",
        "title: Generated Block State",
        "type: generated-read-model",
        "status: generated",
        f"registry_version: {vault.registry.get('version', 'unknown')}",
        "---",
        "",
        "# Generated Block State",
        "",
        "> AUTO-GENERATED by `pos check --write`. Do not edit by hand. Owners below remain the sources of truth.",
        "",
        "## Live block graph",
        "",
        "| Block | Kind | Status | Owner updated | Owner | Reads / depends on |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        link = row.owner.removesuffix(".md")
        deps = ", ".join(row.depends_on) or "—"
        lines.append(
            f"| `{row.id}` | {row.kind} | **{row.status}** | {row.updated} | [[{link}\\|{row.title}]] | {deps} |"
        )
    external = vault.registry.get("external_blocks", [])
    lines += ["", "## External blocks mirrored into the vault", ""]
    if external:
        lines += ["| Block | Kind | Status | External owner |", "|---|---|---|---|"]
        for block in external:
            lines.append(f"| `{block['id']}` | {block['kind']} | **{block['status']}** | `{block['owner']}` |")
    else:
        lines.append("None.")
    lines += [
        "",
        "## How to use this snapshot",
        "",
        "- Read it at every session start to know which blocks exist and which owners may affect the task.",
        "- For semantic changes, follow [[00-meta/block-sync|Cross-Block Sync Contract]]; this table alone cannot infer meaning.",
        "- Refresh and validate with `pos check --write`.",
        "",
    ]
    return "\n".join(lines)


def snapshot_is_fresh(vault: Vault, output: str) -> bool:
    target = vault.path(vault.cfg("generated_snapshot"))
    return target.is_file() and target.read_text(encoding="utf-8") == output


def write_snapshot(vault: Vault, output: str) -> bool:
    target = vault.path(vault.cfg("generated_snapshot"))
    if snapshot_is_fresh(vault, output):
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(output, encoding="utf-8")
    return True


def staged_paths(vault: Vault) -> set[str]:
    result = subprocess.run(
        ["git", "-C", str(vault.root), "diff", "--cached", "--name-only", "--diff-filter=ACMR"],
        check=True,
        capture_output=True,
        text=True,
    )
    return set(result.stdout.splitlines())


_UPDATED = re.compile(r"(?m)^updated:.*$")


def stamp_changed_owners(vault: Vault, changed: set[str], today: str) -> list[str]:
    """Set `updated: <today>` on changed owners whose stamp is stale.

    A file changed today is, by definition, updated today. Doing this in the hook
    keeps the freshness contract true without letting a stale date silently block
    an unattended backup (the failure that motivated this function).
    """
    stamped: list[str] = []
    for block in vault.registry.get("blocks", []):
        owner = block["owner"]
        if owner not in changed:
            continue
        path = vault.path(owner)
        if frontmatter(path).get("updated") == today:
            continue
        text = path.read_text(encoding="utf-8")
        end = text.find("\n---\n", 4)
        head, rest = text[:end], text[end:]
        head = _UPDATED.sub(f"updated: {today}", head, count=1) if _UPDATED.search(head) else head + f"\nupdated: {today}"
        path.write_text(head + rest, encoding="utf-8")
        stamped.append(owner)
    return stamped


def stale_changed_owners(vault: Vault, changed: set[str], today: str) -> list[str]:
    return [
        b["id"]
        for b in vault.registry.get("blocks", [])
        if b["owner"] in changed and frontmatter(vault.path(b["owner"])).get("updated") != today
    ]


def reverse_dependencies(vault: Vault, changed: set[str]) -> list[str]:
    """Blocks that read a changed owner: these need a semantic propagation review."""
    changed_ids = {b["id"] for b in vault.registry.get("blocks", []) if b["owner"] in changed}
    return sorted(
        b["id"] for b in vault.registry.get("blocks", []) if changed_ids.intersection(b.get("depends_on", []))
    )
